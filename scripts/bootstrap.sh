#!/usr/bin/env bash
# Bootstrap a self-contained ESP-IDF installation in one directory.
#
#   scripts/bootstrap.sh <root> [-v <idf-tag>] [-t <targets>]
#   scripts/bootstrap.sh ~/code/esp-idf_5.5.2 -v v5.5.2 -t esp32c3
#
# Everything lands under <root>; nothing is written to ~/.espressif or
# the user caches, so several versions can coexist:
#   <root>/esp-idf     ESP-IDF git checkout (shallow)
#   <root>/tools       IDF_TOOLS_PATH: toolchains, python venv, downloads
#   <root>/cache       pip, component-manager and ccache caches
#   <root>/env.sh      environment variables; sourced by scripts/export.sh
#
# Re-running is safe: an existing checkout is reused and install.sh
# only fetches what is missing. Prerequisites: git, python3 >= 3.9,
# cmake, ninja, dfu-util (brew install cmake ninja dfu-util).
set -euo pipefail

usage() { sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-1}"; }

ROOT=""
IDF_TAG="v5.5.2"
TARGETS="esp32c3"
while [ $# -gt 0 ]; do
    case "$1" in
        -v|--version) IDF_TAG="$2"; shift 2 ;;
        -t|--targets) TARGETS="$2"; shift 2 ;;
        -h|--help)    usage 0 ;;
        -*)           echo "unknown option: $1" >&2; usage ;;
        *)            [ -z "$ROOT" ] || usage; ROOT="$1"; shift ;;
    esac
done
[ -n "$ROOT" ] || usage

for tool in git python3 cmake ninja; do
    command -v "$tool" >/dev/null || { echo "missing prerequisite: $tool" >&2; exit 1; }
done

mkdir -p "$ROOT"
ROOT="$(cd "$ROOT" && pwd)"
IDF_DIR="$ROOT/esp-idf"

# Written first so the install below already uses the encapsulated paths.
cat > "$ROOT/env.sh" <<EOF
# Generated by embpet scripts/bootstrap.sh — sourced by scripts/export.sh.
export IDF_TOOLS_PATH="$ROOT/tools"
export PIP_CACHE_DIR="$ROOT/cache/pip"
export IDF_COMPONENT_CACHE_PATH="$ROOT/cache/component-manager"
export CCACHE_DIR="$ROOT/cache/ccache"
export EMBPET_IDF_ROOT="$ROOT"
export EMBPET_IDF_TAG="$IDF_TAG"
EOF
# shellcheck source=/dev/null
. "$ROOT/env.sh"
mkdir -p "$IDF_TOOLS_PATH" "$PIP_CACHE_DIR" "$IDF_COMPONENT_CACHE_PATH" "$CCACHE_DIR"

if [ -d "$IDF_DIR/.git" ]; then
    have="$(git -C "$IDF_DIR" describe --tags --exact-match 2>/dev/null || echo unknown)"
    if [ "$have" != "$IDF_TAG" ]; then
        echo "error: $IDF_DIR is at '$have', expected '$IDF_TAG'." >&2
        echo "       Use a different <root> per version." >&2
        exit 1
    fi
    echo "==> Reusing ESP-IDF $IDF_TAG checkout in $IDF_DIR"
else
    echo "==> Cloning ESP-IDF $IDF_TAG into $IDF_DIR"
    git clone --depth 1 --branch "$IDF_TAG" https://github.com/espressif/esp-idf.git "$IDF_DIR"
fi

echo "==> Updating submodules"
if ! git -C "$IDF_DIR" submodule update --init --recursive --depth 1 --jobs 8; then
    echo "    shallow submodule fetch failed, retrying with full history" >&2
    git -C "$IDF_DIR" submodule update --init --recursive --jobs 8
fi

echo "==> Installing tools for: $TARGETS (IDF_TOOLS_PATH=$IDF_TOOLS_PATH)"
"$IDF_DIR/install.sh" "$TARGETS"

echo
echo "Done. Activate in a shell with:"
echo "  . $(cd "$(dirname "$0")" && pwd)/export.sh $ROOT"
